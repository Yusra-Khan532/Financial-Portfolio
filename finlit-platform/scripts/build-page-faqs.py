#!/usr/bin/env python3
"""Parse the 'FinLit page FAQs' PDF into frontend/src/content/pageFaqs.ts (+ scripts/data/page-faqs.json).

Usage: python3 scripts/build-page-faqs.py <path-to-finlit-page-faqs.pdf>
Needs pdfplumber. Text is kept verbatim: only line wraps are joined (with one space; a gap bigger than a normal
line step starts a new paragraph, joined with a blank line). Fonts tell the parts apart:
  serif 16.5pt = section, serif 13.5pt = page title, sans-serif semibold = question, sans-serif regular = answer,
  the 'Page: ... . N questions' line = routes, optional plan, expected count.
"""
import json, re, sys, pathlib
import pdfplumber

ROOT = pathlib.Path(__file__).resolve().parent.parent
pdf_path = sys.argv[1]
lines = []
with pdfplumber.open(pdf_path) as pdf:
    for pg in pdf.pages:
        for l in pg.extract_text_lines(return_chars=True):
            ch = [c for c in l["chars"] if not c["text"].isspace()]
            if not ch: continue
            if ch[0]["size"] < 7: continue            # running header and "Page n of 31" footer
            semi = sum("Semibold" in c["fontname"] for c in ch) > len(ch) / 2
            lines.append(dict(text=l["text"].strip(), size=round(ch[0]["size"], 1), semi=semi, top=l["top"], page=pg.page_number))

# skip the cover (everything before the first section heading at 16.5pt)
start = next(i for i, l in enumerate(lines) if l["size"] == 16.5)
end = next(i for i, l in enumerate(lines) if l["text"] == "Check before publishing")  # trailing editorial table, not FAQ content
lines = lines[start:end]

pages, section, cur, mode, prev = [], None, None, None, None
PAGE_RE = re.compile(r"^Page: (.+?)(?: · Plan: (.+?))? · (\d+) questions?$")

def join(parts):  # parts: list of (text, newpara)
    out = ""
    for t, np in parts:
        out = t if not out else out + ("\n\n" if np else " ") + t
    return out

def close_item():
    global mode
    if cur and cur.get("_q"):
        cur["items"].append({"q": join([(t, False) for t in cur["_q"]]), "a": join(cur["_a"])})
    if cur: cur["_q"], cur["_a"] = None, []

for l in lines:
    t = l["text"]
    if l["size"] == 16.5:
        close_item(); section = t; cur = None; continue
    if l["size"] == 13.5:
        close_item(); cur = dict(id="", title=t, section=section, routes=[], items=[], _q=None, _a=[], _n=0); pages.append(cur); prev = None; continue
    m = PAGE_RE.match(t)
    if m and cur is not None and not cur["routes"]:
        cur["routes"] = [r.strip() for r in m.group(1).split(",")]
        if m.group(2): cur["plan"] = m.group(2)
        cur["_n"] = int(m.group(3)); continue
    if l["semi"]:
        if cur["_q"] is not None and not cur["_a"]:   # second line of a wrapped question
            cur["_q"].append(t)
        else:
            close_item(); cur["_q"] = [t]
        prev = l; continue
    # answer line; new paragraph when the vertical step is bigger than a normal wrapped line (18pt) on the same page
    newpara = bool(cur["_a"]) and prev is not None and prev["page"] == l["page"] and not prev["semi"] and (l["top"] - prev["top"]) > 24
    cur["_a"].append((t, newpara)); prev = l
close_item()

out = []
for p in pages:
    n = p.pop("_n"); p.pop("_q"); p.pop("_a")
    assert len(p["items"]) == n, (p["title"], len(p["items"]), n)
    p["declared"] = n
    p["id"] = re.sub(r"[^a-z0-9]+", "-", p["title"].lower()).strip("-")
    out.append(dict(declared=n, id=p["id"], title=p["title"], section=p["section"], routes=p["routes"], **({"plan": p["plan"]} if "plan" in p else {}), items=p["items"]))
assert len(out) == 32 and sum(len(p["items"]) for p in out) == 228, (len(out), sum(len(p["items"]) for p in out))

(ROOT / "scripts/data").mkdir(exist_ok=True)
(ROOT / "scripts/data/page-faqs.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
ts = ("// GENERATED by scripts/build-page-faqs.py from the 'FinLit page FAQs' PDF (Oct 30 2026). Do not edit by hand.\n"
      "// Text is verbatim from the PDF (pre-vetted). 32 pages, 228 questions.\n"
      "export type PageFaq = { id: string; title: string; section: string; routes: string[]; plan?: string; items: { q: string; a: string }[] };\n\n"
      "export const PAGE_FAQS: PageFaq[] = " + json.dumps([{k: v for k, v in p.items() if k != "declared"} for p in out], ensure_ascii=False, indent=1) + ";\n")
(ROOT / "frontend/src/content/pageFaqs.ts").write_text(ts, encoding="utf-8")
print("pages", len(out), "questions", sum(len(p["items"]) for p in out))
